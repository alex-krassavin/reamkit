/**
 * A built-in table style by its name, each region with its format.
 *
 * @param name The style's name as a workbook gives it (`TableStyleMedium2`).
 * @returns Its regions' formats, or undefined for a name Excel does not build in.
 */
export function presetTableStyle(
  name: string,
): Partial<Record<TableStyleElementType, PresetDxf>> | undefined {
  const style = STYLES[name];
  if (!style) return undefined;
  const out: Partial<Record<TableStyleElementType, PresetDxf>> = {};
  for (const [type, i] of Object.entries(style)) {
    out[type as TableStyleElementType] = DXFS[i]!;
  }
  return out;
}
