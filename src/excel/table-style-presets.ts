// §18.8.40 — the table styles Excel has built in, which a workbook names in
// `<tableStyleInfo name>` and never writes down: TableStyleLight1…21,
// TableStyleMedium1…28 and TableStyleDark1…11. Generated from the standard's
// own definitions — ECMA-376 Part 1, the electronic insert
// OfficeOpenXML-SpreadsheetMLStyles.zip, presetTableStyles.xml (whose dxfIds,
// unlike a workbook's, count from one). A colour is a theme slot — 0 lt1, 1
// dk1, 2 lt2, 3 dk2, 4…9 accent1…6 — and the tint applied to it.

import type { TableStyleElementType } from '@/core/spreadsheet-model';

/** A theme colour: its slot and the tint applied to it (0 = none). */
export type PresetColor = readonly [theme: number, tint: number];

/** One line of a preset: its style and colour. */
export type PresetEdge = readonly ['thin' | 'medium' | 'thick' | 'double', PresetColor];

/** A preset's differential format: what one region of a table takes. */
export interface PresetDxf {
  readonly bold?: boolean;
  readonly color?: PresetColor;
  readonly fill?: PresetColor;
  readonly border?: {
    readonly left?: PresetEdge;
    readonly right?: PresetEdge;
    readonly top?: PresetEdge;
    readonly bottom?: PresetEdge;
    readonly vertical?: PresetEdge;
    readonly horizontal?: PresetEdge;
  };
}

