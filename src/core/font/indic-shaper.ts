/** What a face can do for one script, worked out once. */
interface Plan {
  readonly config: ScriptConfig;
  readonly face: OtlFace;
  /** The face's layout is the old one (`deva`, not `dev2`). */
  readonly oldSpec: boolean;
  readonly early: Array<OtlStep>;
  readonly basic: ReadonlyArray<Array<OtlStep>>;
  readonly late: Array<OtlStep>;
  readonly has: ReadonlySet<string>;
  readonly rphf: Array<OtlStep>;
  readonly pref: Array<OtlStep>;
  readonly blwf: Array<OtlStep>;
  readonly pstf: Array<OtlStep>;
  readonly vatu: Array<OtlStep>;
  readonly zeroContext: boolean;
  readonly virama: number;
  /** Below-base, post-base or base: what each consonant glyph turned out to be. */
  readonly consonants: Map<number, number>;
}

const plans = new WeakMap<ParsedTtf, Map<ScriptConfig, Plan | null>>();

function planFor(parsed: ParsedTtf, config: ScriptConfig): Plan | undefined {
  let byScript = plans.get(parsed);
  if (!byScript) {
    byScript = new Map();
    plans.set(parsed, byScript);
  }
  const had = byScript.get(config);
  if (had !== undefined) return had ?? undefined;
  const face = OtlFace.of(parsed);
  const script = pickScript(face.gsub, config.tags);
  if (script === undefined || !(config.tags as ReadonlyArray<string>).includes(script)) {
    byScript.set(config, null);
    return undefined;
  }
  const tags = config.tags;
  const oldSpec = !script.endsWith('2');
  const has = new Set<string>();
  for (const f of [...BASIC, ...PRESENTATION]) {
    if (planLookups(face.gsub, tags, [f]).length > 0) has.add(f.tag);
  }
  const only = (tag: string): Array<OtlStep> =>
    planLookups(face.gsub, tags, [BASIC.find((f) => f.tag === tag)!]);
  const plan: Plan = {
    config,
    face,
    oldSpec,
    early: planLookups(face.gsub, tags, [
      plain('rvrn'),
      plain('ltra'),
      plain('ltrm'),
      { tag: 'locl', mask: GLOBAL, perSyllable: true },
      { tag: 'ccmp', mask: GLOBAL, perSyllable: true },
    ]),
    basic: BASIC.map((f) => planLookups(face.gsub, tags, [f])),
    late: planLookups(face.gsub, tags, PRESENTATION),
    has,
    rphf: only('rphf'),
    pref: only('pref'),
    blwf: only('blwf'),
    pstf: only('pstf'),
    vatu: only('vatu'),
    zeroContext: !oldSpec && config !== SCRIPTS[8]![1],
    virama: parsed.glyphForCodepoint(config.virama),
    consonants: new Map(),
  };
  byScript.set(config, plan);
  return plan;
}

/** The glyphs of a shaped run, in drawing order, with where each is drawn. */
export interface IndicRun {
  readonly gids: Array<number>;
  /** Per glyph: the index, in code points, of the first character of its cluster. */
  readonly clusters: Array<number>;
  /** Per glyph, in font units. */
  readonly advances: Array<number>;
  readonly xOffsets: Array<number>;
  readonly yOffsets: Array<number>;
}

/**
 * Shape a run of text in one face, when the face has OpenType layout for the
 * script of India its text is in.
 *
 * @param parsed The face.
 * @param text   The text.
 * @param kern   Whether to apply the face's `kern` feature (the layout profile decides).
 * @returns The shaped glyphs, or `undefined` when the text holds no letter of
 *          those scripts or the face has no layout for them — the caller's
 *          own shaping applies then.
 */
export function shapeIndic(parsed: ParsedTtf, text: string, kern = true): IndicRun | undefined {
  const cps = [...text].map((ch) => ch.codePointAt(0)!);
  // One run per script, the characters they share going with the run they stand in.
  const runs: Array<{ config: ScriptConfig; from: number; to: number }> = [];
  cps.forEach((cp, i) => {
    const config = scriptOf(cp);
    const last = runs[runs.length - 1];
    if (last && (!config || config === last.config)) last.to = i + 1;
    else if (config) runs.push({ config, from: last ? i : 0, to: i + 1 });
  });
  if (runs.length === 0) return undefined;
  runs[runs.length - 1]!.to = cps.length;
  const out: IndicRun = { gids: [], clusters: [], advances: [], xOffsets: [], yOffsets: [] };
  let shapedAny = false;
  for (const run of runs) {
    const plan = planFor(parsed, run.config);
    // A script the face has no layout for is set glyph by glyph, as it was.
    const shaped = plan
      ? shapeRun(plan, parsed, cps.slice(run.from, run.to), kern)
      : unshaped(parsed, cps.slice(run.from, run.to));
    shapedAny ||= plan !== undefined;
    out.gids.push(...shaped.gids);
    out.clusters.push(...shaped.clusters.map((c) => c + run.from));
    out.advances.push(...shaped.advances);
    out.xOffsets.push(...shaped.xOffsets);
    out.yOffsets.push(...shaped.yOffsets);
  }
  return shapedAny ? out : undefined;
}

/** Each character its own glyph, at its own advance. */
function unshaped(parsed: ParsedTtf, cps: ReadonlyArray<number>): IndicRun {
  const gids = cps.map((cp) => parsed.glyphForCodepoint(cp));
  return {
    gids,
    clusters: cps.map((_, i) => i),
    advances: gids.map((g) => parsed.advanceWidths[g] ?? 0),
    xOffsets: gids.map(() => 0),
    yOffsets: gids.map(() => 0),
  };
}

/** Shape the characters of one script in a face that has its layout. */
function shapeRun(
  plan: Plan,
  parsed: ParsedTtf,
  cps: ReadonlyArray<number>,
  kern: boolean,
): IndicRun {
  const { config } = plan;

  const buf = normalize(parsed, plan.face, cps);
  for (const g of buf) {
    [g.cat, g.pos] = properties(g.cp);
    if (g.cat === ZWJ) g.joiner = 'zwj';
    else if (g.cat === ZWNJ) g.joiner = 'zwnj';
  }
  // Each syllable is numbered (from 1, so that 0 stays "none") and typed.
  let serial = 0;
  for (const [start, end, type] of syllables(buf.map((g) => g.cat))) {
    serial++;
    for (let i = start; i < end; i++) {
      buf[i]!.syllable = serial;
      buf[i]!.type = type;
    }
  }

  substitute(plan.face, plan.early, buf);
  initialReordering(plan, parsed, buf);
  for (const steps of plan.basic) substitute(plan.face, steps, buf);
  finalReordering(plan, buf);
  substitute(plan.face, plan.late, buf);

  const gpos = planLookups(plan.face.gpos, config.tags, [
    ...['abvm', 'blwm', 'curs', 'dist', ...(kern ? ['kern'] : [])].map(plain),
    markFeature('mark'),
    markFeature('mkmk'),
  ]);
  const pos = position(plan.face, gpos, buf);
  removeIgnorables(buf, pos);

  const out: IndicRun = { gids: [], clusters: [], advances: [], xOffsets: [], yOffsets: [] };
  buf.forEach((g, i) => {
    const p = pos[i]!;
    out.gids.push(g.gid);
    out.clusters.push(g.cluster);
    out.advances.push(p.xAdvance);
    out.xOffsets.push(p.xOffset);
    out.yOffsets.push(p.yOffset);
  });
  return out;
}

// Default-ignorable characters a run of these scripts holds: the join
// controls, the zero-width space, the direction marks, the word joiner.
const IGNORABLE = new Set([0x200b, 0x200c, 0x200d, 0x200e, 0x200f, 0x2060, 0xfeff]);

/**
 * Take out what draws nothing, once the lookups are done with it: a join
 * control has decided whether a conjunct forms and whether a mark attaches,
 * and is not drawn. Its cluster goes to a neighbour the way HarfBuzz's
 * `delete_glyph` gives it.
 */
function removeIgnorables(buf: Array<Glyph>, pos: Array<unknown>): void {
  for (let i = 0; i < buf.length; i++) {
    const g = buf[i]!;
    if (!IGNORABLE.has(g.cp) || ligated(g)) continue;
    const prev = buf[i - 1];
    const next = buf[i + 1];
    if (next?.cluster === g.cluster || prev?.cluster === g.cluster) {
      // Its cluster lives on in a neighbour.
    } else if (prev) {
      if (g.cluster < prev.cluster) {
        const old = prev.cluster;
        for (let k = i; k > 0 && buf[k - 1]!.cluster === old; k--) buf[k - 1]!.cluster = g.cluster;
      }
    } else if (next) {
      mergeClusters(buf, i, i + 2);
    }
    buf.splice(i, 1);
    pos.splice(i, 1);
    i--;
  }
}

// An independent vowel and a vowel sign that together read as another
// independent vowel — অ + া for আ, ഒ + ാ for ഓ — are not a spelling of it: the
// letter has its own code point. Microsoft's shaping engine draws the sign on a
// dotted circle there, and HarfBuzz does the same, so that the reader sees
// that something is wrong rather than a vowel that is not in the text. These
// are its pairs (the first character, and the signs that may not follow it).
const VOWEL_CONSTRAINTS: ReadonlyMap<number, ReadonlySet<number>> = new Map(
  (
    [
      [
        0x0905,
        [
          0x093a, 0x093b, 0x093e, 0x0945, 0x0946, 0x0949, 0x094a, 0x094b, 0x094c, 0x094f, 0x0956,
          0x0957,
        ],
      ],
      [0x0906, [0x093a, 0x0945, 0x0946, 0x0947, 0x0948]],
      [0x0909, [0x0941]],
      [0x090f, [0x0945, 0x0946, 0x0947]],
      [0x0985, [0x09be]],
      [0x098b, [0x09c3]],
      [0x098c, [0x09e2]],
      [0x0a05, [0x0a3e, 0x0a48, 0x0a4c]],
      [0x0a72, [0x0a3f, 0x0a40, 0x0a47]],
      [0x0a73, [0x0a41, 0x0a42, 0x0a4b]],
      [0x0a85, [0x0abe, 0x0ac5, 0x0ac7, 0x0ac8, 0x0ac9, 0x0acb, 0x0acc]],
      [0x0ac5, [0x0abe]],
      [0x0b05, [0x0b3e]],
      [0x0b0f, [0x0b57]],
      [0x0b13, [0x0b57]],
      [0x0b85, [0x0bc2]],
      [0x0c12, [0x0c4c, 0x0c55]],
      [0x0c3f, [0x0c55]],
      [0x0c46, [0x0c55]],
      [0x0c4a, [0x0c55]],
      [0x0c89, [0x0cbe]],
      [0x0c8b, [0x0cbe]],
      [0x0c92, [0x0ccc]],
      [0x0d07, [0x0d57]],
      [0x0d09, [0x0d57]],
      [0x0d0e, [0x0d46]],
      [0x0d12, [0x0d3e, 0x0d57]],
    ] as const
  ).map(([first, signs]) => [first, new Set<number>(signs)]),
);

/**
 * The characters with a dotted circle put into each sequence that spells one
 * vowel as another (see {@link VOWEL_CONSTRAINTS}), each with its cluster: the
 * circle takes the cluster of the sign it carries.
 */
function constrainVowels(
  cps: ReadonlyArray<number>,
  clusters: ReadonlyArray<number>,
): Array<readonly [number, number]> {
  const out: Array<readonly [number, number]> = [];
  let i = 0;
  while (i < cps.length) {
    const cp = cps[i]!;
    let matched = i + 1 < cps.length && VOWEL_CONSTRAINTS.get(cp)?.has(cps[i + 1]!) === true;
    // Ra, virama, I reads as vocalic R.
    if (cp === 0x0930 && cps[i + 1] === 0x094d && cps[i + 2] === 0x0907) {
      out.push([cp, clusters[i]!]);
      i++;
      matched = true;
    }
    out.push([cps[i]!, clusters[i]!]);
    i++;
    if (matched && i < cps.length) {
      out.push([0x25cc, clusters[i]!], [cps[i]!, clusters[i]!]);
      i++;
    }
  }
  return out;
}

// ----- Normalization -----

/**
 * Characters to glyphs the way HarfBuzz's normalizer does for these scripts:
 * every grapheme one cluster; a composite taken apart wherever the face has
 * its parts (a nukta letter becomes its letter and the nukta, a two-part vowel
 * sign its two parts); marks in canonical order; and a letter and a mark put
 * back together where the face draws the composite and Unicode allows it.
 */
function normalize(parsed: ParsedTtf, face: OtlFace, cps: ReadonlyArray<number>): Array<Glyph> {
  const glyph = (cp: number): number => parsed.glyphForCodepoint(cp);
  const make = (cp: number, cluster: number): Glyph => {
    const gid = glyph(cp);
    return {
      gid,
      cluster,
      mask: GLOBAL,
      cls: face.glyphClass(gid),
      syllable: 0,
      ligId: 0,
      ligComp: 0,
      cp,
      cat: X,
      pos: END,
      type: NON_INDIC,
    };
  };

  // Clusters: a grapheme is a character and the marks (and ZWJs) after it.
  const clusters: Array<number> = [];
  cps.forEach((cp, i) => {
    const continues = i > 0 && (isMark(cp) || cp === 0x200d);
    clusters.push(continues ? clusters[i - 1]! : i);
  });

  // Decompose.
  const decompose = (cp: number, out: Array<number>): boolean => {
    if (KEEP_WHOLE.has(cp)) return false;
    const parts = DECOMPOSE.get(cp);
    if (!parts) return false;
    const [a, b] = parts;
    if (glyph(b) === 0) return false;
    const mark = out.length;
    if (decompose(a, out)) {
      out.push(b);
      return true;
    }
    out.length = mark;
    if (glyph(a) === 0) return false;
    out.push(a, b);
    return true;
  };
  const buf: Array<Glyph> = [];
  for (const [cp, cluster] of constrainVowels(cps, clusters)) {
    const parts: Array<number> = [];
    if (decompose(cp, parts)) for (const p of parts) buf.push(make(p, cluster));
    else buf.push(make(cp, cluster));
  }

  // Reorder marks by combining class, stable, merging what moves.
  const ccc = (g: Glyph): number => CCC.get(g.cp) ?? 0;
  for (let i = 0; i < buf.length; i++) {
    if (ccc(buf[i]!) === 0) continue;
    let end = i + 1;
    while (end < buf.length && ccc(buf[end]!) !== 0) end++;
    for (let k = i + 1; k < end; k++) {
      let j = k;
      while (j > i && ccc(buf[j - 1]!) > ccc(buf[k]!)) j--;
      if (j === k) continue;
      mergeClusters(buf, j, k + 1);
      const [moved] = buf.splice(k, 1);
      buf.splice(j, 0, moved!);
    }
    i = end;
  }

  // Recompose a mark onto the letter before it, never a mark onto a mark.
  const out: Array<Glyph> = [];
  let starter = -1;
  for (const g of buf) {
    if (isMark(g.cp) && starter >= 0) {
      const s = out[starter]!;
      const prev = out[out.length - 1]!;
      const composed = isMark(s.cp) ? undefined : COMPOSE.get(`${s.cp},${g.cp}`);
      if (
        composed !== undefined &&
        (starter === out.length - 1 || ccc(prev) < ccc(g)) &&
        glyph(composed) !== 0
      ) {
        s.cluster = Math.min(s.cluster, g.cluster);
        s.cp = composed;
        s.gid = glyph(composed);
        s.cls = face.glyphClass(s.gid);
        continue;
      }
    }
    out.push(g);
    if (ccc(g) === 0) starter = out.length - 1;
  }
  return out;
}

// ----- Reordering -----

const ligated = (g: Glyph): boolean => ((g.props ?? 0) & LIGATED) !== 0;
const isOneOf = (g: Glyph, flags: number): boolean => !ligated(g) && (flag(g.cat) & flags) !== 0;
const isConsonant = (g: Glyph): boolean => isOneOf(g, CONSONANTS);
const isJoiner = (g: Glyph): boolean => isOneOf(g, JOINERS);
const isHalant = (g: Glyph): boolean => isOneOf(g, flag(H));

/** Each consonant's form by the face: below-base, post-base, or a base. */
function consonantPosition(plan: Plan, gid: number): number {
  const known = plan.consonants.get(gid);
  if (known !== undefined) return known;
  const v = plan.virama;
  const would = (steps: Array<OtlStep>): boolean =>
    wouldSubstitute(plan.face, steps, [v, gid], plan.zeroContext) ||
    wouldSubstitute(plan.face, steps, [gid, v], plan.zeroContext);
  const pos =
    would(plan.blwf) || would(plan.vatu)
      ? BELOW_C
      : would(plan.pstf) || would(plan.pref)
        ? POST_C
        : BASE_C;
  plan.consonants.set(gid, pos);
  return pos;
}

function eachSyllable(buf: Array<Glyph>, visit: (start: number, end: number) => void): void {
  let start = 0;
  while (start < buf.length) {
    let end = start + 1;
    while (end < buf.length && buf[end]!.syllable === buf[start]!.syllable) end++;
    visit(start, end);
    start = end;
  }
}

function initialReordering(plan: Plan, parsed: ParsedTtf, buf: Array<Glyph>): void {
  if (plan.virama) {
    for (const g of buf) if (g.pos === BASE_C) g.pos = consonantPosition(plan, g.gid);
  }
  insertDottedCircles(parsed, plan.face, buf);
  eachSyllable(buf, (start, end) => {
    const type = buf[start]!.type;
    if (type === SYMBOL_CLUSTER || type === NON_INDIC) return;
    reorderSyllable(plan, buf, start, end);
  });
}

/** A broken cluster — a mark with nothing to sit on — is given a dotted circle to sit on. */
function insertDottedCircles(parsed: ParsedTtf, face: OtlFace, buf: Array<Glyph>): void {
  if (!buf.some((g) => g.type === BROKEN_CLUSTER)) return;
  const gid = parsed.glyphForCodepoint(0x25cc);
  if (!gid) return;
  let last = 0;
  for (let i = 0; i < buf.length; i++) {
    const g = buf[i]!;
    if (g.type !== BROKEN_CLUSTER || g.syllable === last) continue;
    last = g.syllable;
    let at = i;
    while (at < buf.length && buf[at]!.syllable === last && buf[at]!.cat === REPHA) at++;
    buf.splice(at, 0, {
      gid,
      cluster: g.cluster,
      mask: g.mask,
      cls: face.glyphClass(gid),
      syllable: g.syllable,
      ligId: 0,
      ligComp: 0,
      cp: 0x25cc,
      cat: DOTTEDCIRCLE,
      pos: END,
      type: BROKEN_CLUSTER,
    });
    i = at;
  }
}

function reorderSyllable(plan: Plan, buf: Array<Glyph>, start: number, end: number): void {
  const { config } = plan;
  // Kannada: Ra,virama,ZWJ behaves as Ra,ZWJ,virama.
  if (
    config === SCRIPTS[7]![1] &&
    start + 3 <= end &&
    buf[start]!.cat === RA &&
    buf[start + 1]!.cat === H &&
    buf[start + 2]!.cat === ZWJ
  ) {
    mergeClusters(buf, start + 1, start + 3);
    [buf[start + 1], buf[start + 2]] = [buf[start + 2]!, buf[start + 1]!];
  }

  // 1. Find the base consonant.
  let base = end;
  let hasReph = false;
  let limit = start;
  if (
    plan.has.has('rphf') &&
    start + 3 <= end &&
    ((config.rephMode === 'implicit' && !isJoiner(buf[start + 2]!)) ||
      (config.rephMode === 'explicit' && buf[start + 2]!.cat === ZWJ))
  ) {
    const glyphs = [buf[start]!.gid, buf[start + 1]!.gid];
    if (
      wouldSubstitute(plan.face, plan.rphf, glyphs, plan.zeroContext) ||
      (config.rephMode === 'explicit' &&
        wouldSubstitute(plan.face, plan.rphf, [...glyphs, buf[start + 2]!.gid], plan.zeroContext))
    ) {
      limit += 2;
      while (limit < end && isJoiner(buf[limit]!)) limit++;
      base = start;
      hasReph = true;
    }
  } else if (config.rephMode === 'logical' && buf[start]!.cat === REPHA) {
    limit += 1;
    while (limit < end && isJoiner(buf[limit]!)) limit++;
    base = start;
    hasReph = true;
  }
  {
    let i = end;
    let seenBelow = false;
    do {
      i--;
      const g = buf[i]!;
      if (isConsonant(g)) {
        if (g.pos !== BELOW_C && (g.pos !== POST_C || seenBelow)) {
          base = i;
          break;
        }
        if (g.pos === BELOW_C) seenBelow = true;
        base = i;
      } else if (start < i && g.cat === ZWJ && buf[i - 1]!.cat === H) {
        // A ZWJ after a virama asks for a half form, and ends the search.
        break;
      }
    } while (i > limit);
  }
  // A Ra with no other consonant is the base, not a reph.
  if (hasReph && base === start && limit - base <= 2) hasReph = false;

  // 2. Positions.
  for (let i = start; i < base; i++) buf[i]!.pos = Math.min(PRE_C, buf[i]!.pos);
  if (base < end) buf[base]!.pos = BASE_C;
  if (hasReph) buf[start]!.pos = RA_TO_BECOME_REPH;

  // Old-spec fonts: the first post-base virama moves after the last consonant.
  if (plan.oldSpec) {
    const kannada = config === SCRIPTS[7]![1];
    for (let i = base + 1; i < end; i++) {
      if (buf[i]!.cat !== H) continue;
      let j = end - 1;
      for (; j > i; j--) if (isConsonant(buf[j]!) || (kannada && buf[j]!.cat === H)) break;
      if (buf[j]!.cat !== H && j > i) {
        const [t] = buf.splice(i, 1);
        buf.splice(j, 0, t!);
      }
      break;
    }
  }

  // Marks that ride with the character before them take its position.
  {
    let lastPos = 0;
    for (let i = start; i < end; i++) {
      const g = buf[i]!;
      if (flag(g.cat) & (JOINERS | flag(N) | flag(RS) | flag(CM) | flag(H))) {
        g.pos = lastPos;
        if (g.cat === H && g.pos === PRE_M) {
          // A virama does not go with a left matra.
          for (let j = i; j > start; j--) {
            if (buf[j - 1]!.pos !== PRE_M) {
              g.pos = buf[j - 1]!.pos;
              break;
            }
          }
        }
      } else if (g.pos !== SMVD) {
        if (g.cat === MPST && i > start && buf[i - 1]!.cat === SM) buf[i - 1]!.pos = g.pos;
        lastPos = g.pos;
      }
    }
  }
  // A post-base consonant owns what stands between it and the consonant or matra before.
  {
    let last = base;
    for (let i = base + 1; i < end; i++) {
      const g = buf[i]!;
      if (isConsonant(g)) {
        for (let j = last + 1; j < i; j++) if (buf[j]!.pos < SMVD) buf[j]!.pos = g.pos;
        last = i;
      } else if (g.cat === M || g.cat === MPST) last = i;
    }
  }

  // Sort by position, stable, remembering where each came from.
  {
    const slice = buf.slice(start, end);
    slice.forEach((g, k) => (g.ord = k));
    slice.sort((a, b) => a.pos - b.pos || a.ord! - b.ord!);
    for (let i = start; i < end; i++) buf[i] = slice[i - start]!;

    base = end;
    let firstLeft = end;
    let lastLeft = end;
    for (let i = start; i < end; i++) {
      if (buf[i]!.pos === BASE_C) {
        base = i;
        break;
      }
      if (buf[i]!.pos === PRE_M) {
        if (firstLeft === end) firstLeft = i;
        lastLeft = i;
      }
    }
    // Several left matras are drawn in the reverse of the order they are written.
    if (firstLeft < lastLeft) {
      reverse(buf, firstLeft, lastLeft + 1);
      // …each with the nukta or virama it carries still after it.
      let i = firstLeft;
      for (let j = i; j <= lastLeft; j++) {
        if (buf[j]!.cat === M || buf[j]!.cat === MPST) {
          reverse(buf, i, j + 1);
          i = j + 1;
        }
      }
    }

    // What moved after the base merges its cluster with what it moved past.
    if (plan.oldSpec || end - start > 127) mergeClusters(buf, base, end);
    else {
      const seen = new Set<number>();
      const at = (i: number): number => start + buf[i]!.ord!;
      for (let i = base; i < end; i++) {
        if (seen.has(i)) continue;
        let min = i;
        let max = i;
        let j = at(i);
        while (j !== i && !seen.has(j)) {
          min = Math.min(min, j);
          max = Math.max(max, j);
          seen.add(j);
          j = at(j);
        }
        mergeClusters(buf, Math.max(base, min), max + 1);
      }
    }
  }

  // Masks.
  for (let i = start; i < end && buf[i]!.pos === RA_TO_BECOME_REPH; i++) buf[i]!.mask |= RPHF;
  const pre = HALF | (!plan.oldSpec && !config.blwfPostOnly ? BLWF : 0);
  for (let i = start; i < base; i++) buf[i]!.mask |= pre;
  for (let i = base + 1; i < end; i++) buf[i]!.mask |= BLWF | ABVF | PSTF;

  // Old-spec Devanagari: an eyelash Ra under a half form takes its below form.
  if (plan.oldSpec && config === SCRIPTS[0]![1]) {
    for (let i = start; i + 1 < base; i++) {
      if (
        buf[i]!.cat === RA &&
        buf[i + 1]!.cat === H &&
        (i + 2 === base || buf[i + 2]!.cat !== ZWJ)
      ) {
        buf[i]!.mask |= BLWF;
        buf[i + 1]!.mask |= BLWF;
      }
    }
  }

  // A virama and Ra after the base that 'pref' would take is marked for it.
  if (plan.has.has('pref') && base + 2 < end) {
    for (let i = base + 1; i + 1 < end; i++) {
      if (wouldSubstitute(plan.face, plan.pref, [buf[i]!.gid, buf[i + 1]!.gid], plan.zeroContext)) {
        buf[i]!.mask |= PREF;
        buf[i + 1]!.mask |= PREF;
        break;
      }
    }
  }

  // A ZWNJ keeps the consonant before it from taking a half form.
  for (let i = start + 1; i < end; i++) {
    if (!isJoiner(buf[i]!) || buf[i]!.cat !== ZWNJ) continue;
    let j = i;
    do {
      j--;
      buf[j]!.mask &= ~HALF;
    } while (j > start && !isConsonant(buf[j]!));
  }
}

/** Reverse `buf[start..end)` in place. */
function reverse(buf: Array<Glyph>, start: number, end: number): void {
  for (let a = start, b = end - 1; a < b; a++, b--) [buf[a], buf[b]] = [buf[b]!, buf[a]!];
}

function finalReordering(plan: Plan, buf: Array<Glyph>): void {
  eachSyllable(buf, (start, end) => finalSyllable(plan, buf, start, end));
}

function finalSyllable(plan: Plan, buf: Array<Glyph>, start: number, end: number): void {
  const { config } = plan;
  const malayalamOrTamil = config === SCRIPTS[8]![1] || config === SCRIPTS[5]![1];

  // A virama glyph that a ligature took apart again is a virama still.
  if (plan.virama) {
    for (let i = start; i < end; i++) {
      const g = buf[i]!;
      const props = g.props ?? 0;
      if (g.gid === plan.virama && props & LIGATED && props & MULTIPLIED) {
        g.cat = H;
        g.props = props & ~(LIGATED | MULTIPLIED);
      }
    }
  }

  let tryPref = plan.has.has('pref');
  const formed = (g: Glyph): boolean => {
    const props = g.props ?? 0;
    return (props & LIGATED) !== 0 && (props & MULTIPLIED) === 0;
  };

  // Find the base again.
  let base = start;
  for (; base < end; base++) {
    if (buf[base]!.pos < BASE_C) continue;
    if (tryPref && base + 1 < end) {
      for (let i = base + 1; i < end; i++) {
        if ((buf[i]!.mask & PREF) === 0) continue;
        if (!((buf[i]!.props ?? 0) & SUBSTITUTED && formed(buf[i]!))) {
          // A 'pref' candidate that formed nothing: the base is around here.
          base = i;
          while (base < end && isHalant(buf[base]!)) base++;
          if (base < end) buf[base]!.pos = BASE_C;
          tryPref = false;
        }
        break;
      }
      if (base === end) break;
    }
    // Malayalam: skip over below-base forms that did not form.
    if (config === SCRIPTS[8]![1]) {
      for (let i = base + 1; i < end; i++) {
        while (i < end && isJoiner(buf[i]!)) i++;
        if (i === end || !isHalant(buf[i]!)) break;
        i++;
        while (i < end && isJoiner(buf[i]!)) i++;
        if (i < end && isConsonant(buf[i]!) && buf[i]!.pos === BELOW_C) {
          base = i;
          buf[base]!.pos = BASE_C;
        }
      }
    }
    if (start < base && buf[base]!.pos > BASE_C) base--;
    break;
  }
  if (base === end && start < base && isOneOf(buf[base - 1]!, flag(ZWJ))) base--;
  if (base < end) {
    while (start < base && isOneOf(buf[base]!, flag(N) | flag(H))) base--;
  }

  // Move a pre-base matra closer to the base: after the last standalone virama.
  if (start + 1 < end && start < base) {
    let newPos = base === end ? base - 2 : base - 1;
    if (!malayalamOrTamil) {
      for (;;) {
        while (newPos > start && !isOneOf(buf[newPos]!, flag(M) | flag(MPST) | flag(H))) newPos--;
        if (isHalant(buf[newPos]!) && buf[newPos]!.pos !== PRE_M) {
          // A ZWJ after this virama keeps the matra from moving past it.
          if (newPos + 1 < end && buf[newPos + 1]!.cat === ZWJ && newPos > start) {
            newPos--;
            continue;
          }
        } else newPos = start;
        break;
      }
    }
    if (start < newPos && buf[newPos]!.pos !== PRE_M) {
      for (let i = newPos; i > start; i--) {
        if (buf[i - 1]!.pos !== PRE_M) continue;
        const old = i - 1;
        if (old < base && base <= newPos) base--;
        const [t] = buf.splice(old, 1);
        buf.splice(newPos, 0, t!);
        mergeClusters(buf, newPos, Math.min(end, base + 1));
        newPos--;
      }
    } else {
      for (let i = start; i < base; i++) {
        if (buf[i]!.pos === PRE_M) {
          mergeClusters(buf, i, Math.min(end, base + 1));
          break;
        }
      }
    }
  }

  // Move the reph to where the script draws it.
  if (
    start + 1 < end &&
    buf[start]!.pos === RA_TO_BECOME_REPH &&
    (buf[start]!.cat === REPHA) !== formed(buf[start]!)
  ) {
    const afterHalant = (): number | undefined => {
      let p = start + 1;
      while (p < base && !isHalant(buf[p]!)) p++;
      if (p < base && isHalant(buf[p]!)) {
        if (p + 1 < base && isJoiner(buf[p + 1]!)) p++;
        return p;
      }
      return undefined;
    };
    let target: number | undefined;
    const rephPos = config.rephPos;
    if (rephPos !== AFTER_POST) {
      target = afterHalant();
      if (target === undefined && rephPos === AFTER_MAIN) {
        let p = base;
        while (p + 1 < end && buf[p + 1]!.pos <= AFTER_MAIN) p++;
        if (p < end) target = p;
      }
      if (target === undefined && rephPos === AFTER_SUB) {
        let p = base;
        while (
          p + 1 < end &&
          !(flag(buf[p + 1]!.pos) & (flag(POST_C) | flag(AFTER_POST) | flag(SMVD)))
        ) {
          p++;
        }
        if (p < end) target = p;
      }
    }
    target ??= afterHalant();
    if (target === undefined) {
      let p = end - 1;
      while (p > start && buf[p]!.pos === SMVD) p--;
      // After a matra and a virama, the reph goes before the virama.
      if (isHalant(buf[p]!)) {
        for (let i = base + 1; i < p; i++) if (buf[i]!.cat === M || buf[i]!.cat === MPST) p--;
      }
      target = p;
    }
    mergeClusters(buf, start, target + 1);
    const [reph] = buf.splice(start, 1);
    buf.splice(target, 0, reph!);
    if (start < base && base <= target) base--;
  }

  // Move a pre-base-reordering consonant that formed to before the base.
  if (tryPref && base + 1 < end) {
    for (let i = base + 1; i < end; i++) {
      if ((buf[i]!.mask & PREF) === 0) continue;
      if (formed(buf[i]!)) {
        let newPos = base;
        if (!malayalamOrTamil) {
          while (newPos > start && !isOneOf(buf[newPos - 1]!, flag(M) | flag(MPST) | flag(H))) {
            newPos--;
          }
        }
        if (newPos > start && isHalant(buf[newPos - 1]!)) {
          if (newPos < end && isJoiner(buf[newPos]!)) newPos++;
        }
        mergeClusters(buf, newPos, i + 1);
        const [t] = buf.splice(i, 1);
        buf.splice(newPos, 0, t!);
        if (newPos <= base && base < i) base++;
      }
      break;
    }
  }

  // 'init' on a left matra that starts a word.
  if (buf[start]!.pos === PRE_M) {
    const prev = start > 0 ? buf[start - 1]! : undefined;
    if (!prev || !WORDISH_RE.test(String.fromCodePoint(prev.cp))) buf[start]!.mask |= INIT;
  }
}
