/** The script whose block a code point is in, or `undefined` for one shared by all. */
function scriptOf(cp: number): ScriptConfig | undefined {
  // The Vedic extensions are marks of several scripts and take the one they stand in.
  if (cp >= 0xa8e0 && cp <= 0xa8ff) return SCRIPTS[0]![1];
  if (cp < 0x0900 || cp > 0x0d7f) return undefined;
  // The two dandas are written in every one of them, and the four Vedic
  // accents of the Devanagari block are marks of any.
  if (cp === 0x0964 || cp === 0x0965 || (cp >= 0x0951 && cp <= 0x0954)) return undefined;
  return SCRIPTS[(cp - 0x0900) >> 7]![1];
}

/**
 * Whether a string holds a letter of one of the scripts this shapes.
 *
 * @param text The text.
 * @returns `true` when one of its characters is in their blocks.
 */
export function hasIndic(text: string): boolean {
  for (let i = 0; i < text.length; i++) {
    const c = text.charCodeAt(i);
    if (c >= 0x0900 && c <= 0x0d7f && c !== 0x0964 && c !== 0x0965) return true;
  }
  return false;
}

