// The scripts of India, shaped: Devanagari, Bengali, Gurmukhi, Gujarati, Odia,
// Tamil, Telugu, Kannada and Malayalam.
//
// A word in any of them is not drawn in the order it is written. The short i
// of हिन्दी is typed after the ha it belongs to and drawn before it. The na,
// virama and da are three characters and one conjunct. A Ra that starts a
// syllable rides on top of its last letter as a reph, and a Tamil or Malayalam
// vowel sign may be written once and drawn in two parts, one on each side of
// its consonant. Which of these a face does is up to the face, through
// OpenType's Indic features. Putting the glyphs in the order those features
// expect, and running each feature on the glyphs it belongs to, is the
// shaper's job. Drawn without it, every vowel sign in a line of Hindi stood
// after its consonant and every conjunct came apart.
//
// This is HarfBuzz's Indic shaper (hb-ot-shaper-indic), the one LibreOffice,
// Chrome and Android use, step for step, so that a word comes out in the glyphs
// those renderers draw: normalization, syllables, initial reordering, the basic
// features one at a time, final reordering, the presentation features, then
// GPOS. The character properties it works from are Unicode's
// Indic_Syllabic_Category and Indic_Positional_Category, mapped the way
// HarfBuzz maps them, in `indic-table.ts`. That file is generated by
// scripts/build-indic-table.ts.

