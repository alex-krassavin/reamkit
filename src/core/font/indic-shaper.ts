// A pattern over categories, matched without backtracking: Thompson's
// construction, run as a set of states. HarfBuzz compiles the same grammar
// with Ragel; a backtracking regular expression over it would go quadratic,
// or worse, on a run of join controls.
type Pattern =
  | { readonly kind: 'sym'; readonly set: number }
  | { readonly kind: 'seq' | 'alt'; readonly parts: ReadonlyArray<Pattern> }
  | { readonly kind: 'opt' | 'star'; readonly part: Pattern };

const sym = (...cats: Array<number>): Pattern => ({
  kind: 'sym',
  set: cats.reduce((m, c) => m | flag(c), 0),
});
const seq = (...parts: Array<Pattern>): Pattern => ({ kind: 'seq', parts });
const alt = (...parts: Array<Pattern>): Pattern => ({ kind: 'alt', parts });
const opt = (part: Pattern): Pattern => ({ kind: 'opt', part });
const star = (part: Pattern): Pattern => ({ kind: 'star', part });

interface Nfa {
  /** Per state: the categories it steps on, and where to. */
  readonly on: Array<number>;
  readonly to: Array<number>;
  /** Per state: where it goes without a step. */
  readonly free: Array<Array<number>>;
  readonly start: number;
  readonly accept: number;
}

function compile(pattern: Pattern): Nfa {
  const on: Array<number> = [];
  const to: Array<number> = [];
  const free: Array<Array<number>> = [];
  const state = (): number => {
    on.push(0);
    to.push(-1);
    free.push([]);
    return on.length - 1;
  };
  const build = (p: Pattern): readonly [number, number] => {
    const s = state();
    const e = state();
    switch (p.kind) {
      case 'sym':
        on[s] = p.set;
        to[s] = e;
        break;
      case 'seq': {
        let at = s;
        for (const part of p.parts) {
          const [ps, pe] = build(part);
          free[at]!.push(ps);
          at = pe;
        }
        free[at]!.push(e);
        break;
      }
      case 'alt':
        for (const part of p.parts) {
          const [ps, pe] = build(part);
          free[s]!.push(ps);
          free[pe]!.push(e);
        }
        break;
      case 'opt': {
        const [ps, pe] = build(p.part);
        free[s]!.push(ps, e);
        free[pe]!.push(e);
        break;
      }
      case 'star': {
        const [ps, pe] = build(p.part);
        free[s]!.push(ps, e);
        free[pe]!.push(ps, e);
        break;
      }
    }
    return [s, e];
  };
  const [start, accept] = build(pattern);
  return { on, to, free, start, accept };
}

/** How long a match of `nfa` from `from` can be, up to `limit`; 0 for none. */
function longest(nfa: Nfa, cats: ReadonlyArray<number>, from: number, limit: number): number {
  const close = (states: Iterable<number>): Set<number> => {
    const out = new Set<number>();
    const stack = [...states];
    while (stack.length > 0) {
      const s = stack.pop()!;
      if (out.has(s)) continue;
      out.add(s);
      for (const t of nfa.free[s]!) stack.push(t);
    }
    return out;
  };
  let states = close([nfa.start]);
  let best = 0;
  for (let i = from; i < cats.length && i - from < limit; i++) {
    const bit = flag(cats[i]!);
    const next: Array<number> = [];
    for (const s of states) if (nfa.on[s]! & bit) next.push(nfa.to[s]!);
    if (next.length === 0) break;
    states = close(next);
    if (states.has(nfa.accept)) best = i - from + 1;
  }
  return best;
}

// HarfBuzz's syllable grammar (hb-ot-shaper-indic-machine.rl).
const RULES: ReadonlyArray<readonly [number, Nfa]> = (() => {
  const c = sym(C, RA);
  const n = seq(opt(seq(opt(sym(ZWNJ)), sym(RS))), opt(seq(sym(N), opt(sym(N)))));
  const z = sym(ZWJ, ZWNJ);
  const reph = alt(seq(sym(RA), sym(H)), sym(REPHA));
  const cn = seq(c, opt(sym(ZWJ)), opt(n));
  const symbol = seq(sym(SYMBOL), opt(sym(N)));
  const matraGroup = seq(
    star(z),
    alt(sym(M), seq(opt(sym(SM)), sym(MPST))),
    opt(sym(N)),
    opt(sym(H)),
  );
  const syllableTail = seq(opt(seq(opt(z), sym(SM), opt(sym(SM)), opt(sym(ZWNJ)))), star(sym(A)));
  const halantGroup = seq(opt(z), sym(H), opt(seq(sym(ZWJ), opt(sym(N)))));
  const finalHalantGroup = alt(halantGroup, seq(sym(H), sym(ZWNJ)));
  const halantOrMatraGroup = alt(finalHalantGroup, star(matraGroup));
  const tail = seq(star(seq(halantGroup, cn)), opt(sym(CM)), halantOrMatraGroup, syllableTail);
  return [
    [CONSONANT_SYLLABLE, compile(seq(opt(sym(REPHA, CS)), cn, tail))],
    [VOWEL_SYLLABLE, compile(seq(opt(reph), sym(V), opt(n), alt(sym(ZWJ), tail)))],
    [
      STANDALONE_CLUSTER,
      compile(
        seq(
          alt(seq(opt(sym(REPHA, CS)), sym(PLACEHOLDER)), seq(opt(reph), sym(DOTTEDCIRCLE))),
          opt(n),
          tail,
        ),
      ),
    ],
    [SYMBOL_CLUSTER, compile(seq(symbol, syllableTail))],
    [BROKEN_CLUSTER, compile(seq(opt(reph), opt(n), tail))],
  ];
})();

// No real syllable is half this long; the bound keeps the scan linear whatever
// the text.
const MAX_SYLLABLE = 64;

/** Cut a run of categories into syllables, longest match first: [start, end, type] each. */
function syllables(cats: ReadonlyArray<number>): Array<readonly [number, number, number]> {
  const out: Array<readonly [number, number, number]> = [];
  let i = 0;
  while (i < cats.length) {
    let len = 0;
    let type = NON_INDIC;
    for (const [t, nfa] of RULES) {
      const l = longest(nfa, cats, i, MAX_SYLLABLE);
      if (l > len) {
        len = l;
        type = t;
      }
    }
    if (len === 0) len = 1;
    out.push([i, i + len, type]);
    i += len;
  }
  return out;
}

/**
 * Where the syllables of the scripts of India begin in a text, by the grammar
 * the shaper cuts them with: a syllable is the unit a reph, a conjunct or a
 * vowel sign is shaped within, and shaped in two halves it falls apart.
 *
 * @param text The text.
 * @returns Per code point: whether a syllable — or anything that is not one —
 *          begins at it.
 */
export function syllableStarts(text: string): Array<boolean> {
  const cats = [...text].map((ch) => properties(ch.codePointAt(0)!)[0]);
  const out = cats.map(() => false);
  for (const [start] of syllables(cats)) out[start] = true;
  return out;
}

