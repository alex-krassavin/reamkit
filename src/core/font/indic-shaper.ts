/** A character's category and position; X and END for one the scripts do not use. */
function properties(cp: number): readonly [number, number] {
  let table: string | undefined;
  let at = 0;
  if (cp >= 0x0900 && cp <= 0x0d7f) {
    table = MAIN;
    at = cp - 0x0900;
  } else if (cp >= 0x1cd0 && cp <= 0x1cff) {
    table = VEDIC;
    at = cp - 0x1cd0;
  } else if (cp >= 0xa8e0 && cp <= 0xa8ff) {
    table = EXTENDED;
    at = cp - 0xa8e0;
  }
  if (table === undefined) return SINGLE.get(cp) ?? [X, END];
  return [DIGITS.indexOf(table[2 * at]!), DIGITS.indexOf(table[2 * at + 1]!)];
}

