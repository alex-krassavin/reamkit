/**
 * The text a glyph name stands for, or `undefined` when the name says nothing.
 *
 * @param name The name as `/Differences` (or a font program's charset) gives it.
 */
export function textForGlyphName(name: string): string | undefined {
  // §9.6.6.1 — a name may carry a variant suffix (`five.os` is the oldstyle
  // five, `a.sc` the small capital); the suffix is a shape, not a character.
  const base = name.includes('.') ? (name.split('.')[0] ?? name) : name;
  if (base === '') return undefined;
  // A ligature name joins its parts with underscores: `f_i` is "fi".
  if (base.includes('_')) {
    const parts = base.split('_').map((p) => textForGlyphName(p));
    return parts.every((p) => p !== undefined) ? parts.join('') : undefined;
  }
  const known = GLYPHS[base];
  if (known !== undefined) return known;
  // A single letter or digit names itself.
  if (base.length === 1) return base;
  // The two algorithmic forms: `uniXXXX` (one or more) and `uXXXX`..`uXXXXXX`.
  const uni = /^uni((?:[0-9A-Fa-f]{4})+)$/u.exec(base);
  if (uni) {
    const hex = uni[1]!;
    let out = '';
    for (let i = 0; i < hex.length; i += 4)
      out += String.fromCodePoint(parseInt(hex.slice(i, i + 4), 16));
    return out;
  }
  const u = /^u([0-9A-Fa-f]{4,6})$/u.exec(base);
  if (u) {
    const cp = parseInt(u[1]!, 16);
    return cp <= 0x10ffff ? String.fromCodePoint(cp) : undefined;
  }
  // Annex D.6 — `a38` is a PICTURE, and the dingbats name theirs that way.
  const dingbat = dingbatChar(base);
  if (dingbat !== undefined) return dingbat;
  // `gNN` / `cidNN` / `index42` name a slot in the program, not a character.
  return undefined;
}
