// §9.6.2.2 / Annex D.6 — the ZapfDingbats face, which is one of the fourteen a
// PDF may use without embedding anything.
//
// It is a font of PICTURES with an encoding of its own: code 0x4B is not the
// letter K but `a38`, the six-pointed star ✫, and the names run a1..a202 in an
// order Adobe published rather than any obvious one. Read through the standard
// Latin encoding — which is what a reader does when a font states none —
// ZapfDingbats.pdf's five hundred pictures came back as the alphabet.
//
// The table below is that encoding together with the glyph list: each entry is
// the code, the number in its `aNN` name, and the character it stands for. It
// was transcribed from ZapfDingbats.pdf itself, which is the XSL test suite's
// conformance test for exactly this repertory and prints all 201 of them —
// code, name and code point, one to a row.

/** The character a ZapfDingbats code stands for, or `undefined` for an unused one. */
export function zapfDingbatsChar(code: number): string | undefined {
  const cp = BY_CODE.get(code);
  return cp === undefined ? undefined : String.fromCodePoint(cp);
}

/**
 * The character a dingbat's glyph NAME stands for — `a38` is ✫ — for a font
 * that names its glyphs through `/Differences` (§9.6.6.1).
 *
 * @param name The glyph name.
 */
export function dingbatChar(name: string): string | undefined {
  const found = /^a(\d{1,3})$/u.exec(name);
  const cp = found ? BY_NAME.get(Number(found[1])) : undefined;
  return cp === undefined ? undefined : String.fromCodePoint(cp);
}

/** Whether a base font names the ZapfDingbats face (§9.6.2.2 Table 109). */
export function isZapfDingbats(baseFont: string): boolean {
  return /^(?:[a-z]{6}\+)?zapfdingbats$/u.test(baseFont.trim().toLowerCase());
}

